<?php

namespace App\Http\Controllers\Seller;

use App\Http\Controllers\Controller;
use App\Models\Invoice;
use App\Models\Order;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Http\Request;

class OrderController extends Controller
{
    public function index(Request $request)
    {
        $seller = $request->user()->seller;

        $items = $seller->orderItems()
            ->with(['order.customer', 'order.address', 'product'])
            ->orderByDesc('created_at')
            ->paginate(15);

        return view('seller.orders', ['seller' => $seller, 'items' => $items]);
    }

    public function show(Request $request, Order $order)
    {
        $seller = $request->user()->seller;
        $myItems = $this->authorizeAndLoadItems($request, $order);

        return view('seller.order-show', [
            'seller' => $seller,
            'order' => $order->load(['customer', 'address']),
            'items' => $myItems,
            'isSoleSeller' => $order->items()->where('seller_id', '!=', $seller->id)->doesntExist(),
        ]);
    }

    /**
     * A printable packing slip for just this seller's own items in the
     * order — ship-to address plus product/quantity, no pricing — so a
     * seller shipping their portion of a multi-vendor order never sees or
     * exposes another seller's line items or revenue.
     */
    public function packingSlip(Request $request, Order $order)
    {
        $seller = $request->user()->seller;
        $myItems = $this->authorizeAndLoadItems($request, $order);

        $pdf = Pdf::loadView('seller.packing-slip-pdf', [
            'seller' => $seller,
            'order' => $order->load(['customer', 'address']),
            'items' => $myItems,
        ])->setPaper('a4');

        return $pdf->stream('Packing-Slip-'.$order->order_no.'.pdf');
    }

    /**
     * The full GST tax invoice is order-level (one subtotal/GST/total for
     * every seller's items combined), so it's only handed to a seller when
     * every item on the order is theirs — otherwise it would leak other
     * sellers' revenue on the same order.
     */
    public function generateInvoice(Request $request, Order $order)
    {
        $seller = $request->user()->seller;
        $this->authorizeAndLoadItems($request, $order);
        abort_unless($order->items()->where('seller_id', '!=', $seller->id)->doesntExist(), 403, 'This order includes another seller\'s items — invoices for shared orders are generated by Hardware Centers.');

        Invoice::generateForOrder($order, null);

        return back()->with('status', 'Invoice generated.');
    }

    public function invoicePdf(Request $request, Order $order)
    {
        $seller = $request->user()->seller;
        $this->authorizeAndLoadItems($request, $order);
        abort_unless($order->items()->where('seller_id', '!=', $seller->id)->doesntExist(), 403);

        $invoice = $order->invoice;
        abort_unless($invoice, 404, 'No invoice has been generated for this order yet.');

        $invoice->load(['order.items.product.hsnCode', 'order.items.productVariant', 'customer']);

        $pdf = Pdf::loadView('admin.invoice-pdf', [
            'invoice' => $invoice,
            'order' => $invoice->order,
            'lineItems' => $invoice->lineItems(),
        ])->setPaper('a4');

        $filename = str_replace(['/', '\\'], '-', $invoice->invoice_number).'.pdf';

        return $pdf->stream($filename);
    }

    /**
     * Confirms this seller actually has items on the order (a seller has no
     * business viewing/printing anything for an order they weren't part of)
     * and returns just their own line items.
     */
    private function authorizeAndLoadItems(Request $request, Order $order)
    {
        $seller = $request->user()->seller;
        $myItems = $order->items()->where('seller_id', $seller->id)->with(['product', 'productVariant'])->get();

        abort_if($myItems->isEmpty(), 403);

        return $myItems;
    }
}
